// 5. Check whether a given character is a vowel or a consonant using a multi-level
// if-else structure.
let char = "a";

if (char === "a") {
  console.log("Vowel");
} else if (char === "e") {
  console.log("Vowel");
} else if (char === "i") {
  console.log("Vowel");
} else if (char === "o") {
  console.log("Vowel");
} else if (char === "u") {
  console.log("Vowel");
} else {
  console.log("Consonant");
}
